# ---- H: pointwise algebra of ev, cr ------------------------------------------------------------
print("H  algebra generated by ev_X, cr_alpha of k bodies on Lambda(R^4) (16 x 16 matrices)")


def wedge_mat(vec):
    basis = [b for kk in range(5) for b in itertools.combinations(range(4), kk)]
    pos = {b: i for i, b in enumerate(basis)}
    M = sp.zeros(16, 16)
    for j, b in enumerate(basis):
        for i in range(4):
            if i in b:
                continue
            idx = (i,) + b
            M[pos[tuple(sorted(idx))], j] += perm_sign(idx) * vec[i]
    return M


def ev_mat(vec):
    basis = [b for kk in range(5) for b in itertools.combinations(range(4), kk)]
    pos = {b: i for i, b in enumerate(basis)}
    M = sp.zeros(16, 16)
    for j, b in enumerate(basis):
        for p, i in enumerate(b):
            M[pos[b[:p] + b[p + 1:]], j] += (-1) ** p * vec[i]
    return M


def alg_dim(gens):
    span = [sp.eye(16)]
    vecs = sp.Matrix([list(sp.eye(16))])
    frontier = [sp.eye(16)]
    while frontier:
        new = []
        for Mx in frontier:
            for Gn in gens:
                P = Gn * Mx
                cand = vecs.col_join(sp.Matrix([list(P)]))
                if cand.rank() > vecs.rank():
                    vecs = cand
                    new.append(P)
        frontier = new
    return vecs.rank()


