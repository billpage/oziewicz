def jets_of(Ap):
    """Jets at 0 of a transformed A, read off as Taylor coefficients: c -> value, e -> value."""
    sub = {}
    for i in range(3):
        P_ = sp.Poly(sp.expand(Ap[i]), t, x, y, z)
        for j in range(T + 1):
            sub[c[i][j]] = P_.coeff_monomial(t**j) * sp.factorial(j)
            for k in range(3):
                sub[e[i][j][k]] = P_.coeff_monomial(t**j * xs3[k]) * sp.factorial(j)
    return sub


# ---- ansatz (GL(3)-equivariant, weight <= 2) -------------------------------------------------
p = sp.symbols(f"p0:{N + 2}")                                   # dt ^ d_t^j A
q = sp.symbols(f"q0:{N + 1}")                                   # d_x d_t^j A
pairs = [(j, l) for j in range(N + 2) for l in range(j + 1, N + 2)]
r = {jl: sp.Symbol(f"r{jl[0]}{jl[1]}") for jl in pairs}         # d_t^j A ^ d_t^l A
UNK = list(p) + list(q) + list(r.values())


def comp0(cc, i):                                              # D_{0i}
    return sum(p[j] * cc[i][j] for j in range(N + 2))


def compS(cc, ee, k, i):                                       # D_{ki}, coefficient of dx^k ^ dx^i
    lin = sum(q[j] * (ee[i][j][k] - ee[k][j][i]) for j in range(N + 1))
    quad = sum(r[(j, l)] * (cc[k][j] * cc[i][l] - cc[i][j] * cc[k][l]) for (j, l) in pairs)
    return lin + quad


def subst_cc(sub):
    cc = [[sub[c[i][j]] for j in range(T + 1)] for i in range(3)]
    ee = [[[sub[e[i][j][k]] for k in range(3)] for j in range(T + 1)] for i in range(3)]
    return cc, ee


def lin_eqs(exprs, vars_):
    eqs = []
    for ex in exprs:
        ex = sp.expand(ex)
        if ex == 0:
            continue
        poly = sp.Poly(ex, *vars_)
        eqs += [co for co in poly.coeffs()]
    return eqs


