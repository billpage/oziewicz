import itertools
import sympy as sp

FAILED = []


def check(name, cond):
    ok = bool(cond)
    print(("  ok    " if ok else "  FAIL  ") + name, flush=True)
    if not ok:
        FAILED.append(name)


# ---- forms on R^4 as {sorted index tuple: coefficient} --------------------------------------
SIMPLIFY = True                    # Part K works with polynomials only and switches this off for speed


def clean(f):
    out = {}
    for k, v in f.items():
        v = sp.simplify(v) if SIMPLIFY else sp.expand(v)
        if v != 0:
            out[k] = v
    return out


def add(*fs):
    out = {}
    for f in fs:
        for k, v in f.items():
            out[k] = out.get(k, 0) + v
    return clean(out)


def scale(c, f):
    return clean({k: c * v for k, v in f.items()})


def perm_sign(seq):
    s, seq = 1, list(seq)
    for i in range(len(seq)):
        for j in range(i + 1, len(seq)):
            if seq[i] > seq[j]:
                s = -s
    return s


def wedge(f, g):
    out = {}
    for a, ca in f.items():
        for b, cb in g.items():
            if set(a) & set(b):
                continue
            idx = a + b
            out[tuple(sorted(idx))] = out.get(tuple(sorted(idx)), 0) + perm_sign(idx) * ca * cb
    return clean(out)


def d(f, xs):
    out = {}
    for a, ca in f.items():
        for i, x in enumerate(xs):
            if i in a:
                continue
            idx = (i,) + a
            out[tuple(sorted(idx))] = out.get(tuple(sorted(idx)), 0) + perm_sign(idx) * sp.diff(ca, x)
    return clean(out)


def interior(V, f):
    out = {}
    for a, ca in f.items():
        for pos, i in enumerate(a):
            rest = a[:pos] + a[pos + 1:]
            out[rest] = out.get(rest, 0) + (-1) ** pos * V[i] * ca
    return clean(out)


def lie(V, f, xs):
    return add(interior(V, d(f, xs)), d(interior(V, f), xs))


def iszero(f):
    return clean(f) == {}


def eq(f, g):
    return iszero(add(f, scale(-1, g)))


def one(i):
    return {(i,): sp.Integer(1)}


