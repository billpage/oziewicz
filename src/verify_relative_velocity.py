"""Exact checks for supplement/bodies_first.md.

Parts A to D are exact (SymPy). Parts G and W are numerical: they evaluate
standard formulas with measured constants and are labelled as such.

Conventions: signature (-,+,+,+) and c = 1, as in *Concepts of relative
velocity* (Oziewicz and Page 2011), where a body is a unit time-like vector,
E.E = -1, and the Lorentz boost generated by the bivector E^w with E.w = 0 is

    L_{E^w} x = x - {(gamma-1)(E.x) - (w.x)} E - (E.x - (w.x)/(gamma+1)) w,
    gamma = sqrt(1 + w.w).

Concepts calls the solution w of L_{E^w} S = B, E.w = 0, the (unbounded)
velocity of the bus B relative to the street S as observed by the eagle E:
the ternary velocity w(E, S, B).  The binary velocity of Many-body
mass-centre (1.4.7) is v_SB = B/gamma_SB - S, gamma_SB = -S.B.

Parts
  A  the Concepts boost formula is an isometry and sends E to gamma E + w
  B  eagles in the plane of S and B (E = S, E = B and every other) all give
     the same boost; w(S,S,B) = gamma v_SB and w(B,S,B) = -gamma v_BS
  C  an eagle outside that plane: the unique ternary velocity differs from
     the binary one in size and direction; the two boosts differ by a
     rotation of S's rest space (Thomas-Wigner); w/gamma_w is the Einstein
     velocity v with v (+) u_S = u_B in the eagle's frame
  D  the metric-free split (Def. 1.4.2) and Galilean additivity (1.4.8)
  E  the closed forms of Ternary relative velocity (Oziewicz 2007): (2.2)
     solves the boost-link problem and is reciprocal (2.3); (2.4) is the
     gamma of the boost parameter, not -A.B; for P = A both reduce to the
     binary velocity; for a coplanar P, (2.2) is the form (2.5) and
     gamma = -A.B (Theorem 2.5); (v_AB + v_BA)^2 = -2(gamma-1)(1-1/gamma^2)
  F  (4.2) of the same paper: the 'Lorentz-group' and 'groupoid' values are
     two different quantities of standard relativity
  G  the GZK threshold is an invariant-mass condition (exact form), with
     its numerical value
  W  sizes of v^2/c^2 for the applications withdrawn in the supplement

Run:  PYTHONPATH=src python3 -u src/verify_relative_velocity.py
Writes no files.
"""

from __future__ import annotations

import sympy as sp

FAILED: list[str] = []


def check(name: str, ok: bool) -> None:
    print(f"  [{'ok' if ok else 'FAIL'}] {name}")
    if not ok:
        FAILED.append(name)


def zero(expr) -> bool:
    e = sp.Matrix(expr) if hasattr(expr, "shape") else sp.Matrix([expr])
    return all(sp.simplify(sp.expand(x.rewrite(sp.exp))) == 0 for x in e)


def eta(n: int) -> sp.Matrix:
    return sp.diag(-1, *([1] * (n - 1)))


def dot(a, b, n):
    return (a.T * eta(n) * b)[0, 0]


def boost(E, w, n, gam=None) -> sp.Matrix:
    """Matrix of L_{E^w} from the Concepts formula (columns = images of basis).

    gam defaults to sqrt(1 + w.w); pass it explicitly when SymPy cannot reduce
    the square root (e.g. sqrt(1 + sinh(r)**2) = cosh(r))."""
    if gam is None:
        gam = sp.sqrt(1 + dot(w, w, n))
    cols = []
    for k in range(n):
        x = sp.zeros(n, 1)
        x[k] = 1
        Ex, wx = dot(E, x, n), dot(w, x, n)
        cols.append(x - ((gam - 1) * Ex - wx) * E - (Ex - wx / (gam + 1)) * w)
    return sp.Matrix.hstack(*cols)


# -------------------------------------------------------------------- Part A
def part_a():
    print("A. The boost formula of Concepts of relative velocity")
    n = 4
    w = sp.Matrix([0, *sp.symbols("w1:4", real=True)])
    E = sp.Matrix([1, 0, 0, 0])
    L = boost(E, w, n)
    check("L_{E^w} is an isometry (symbolic w in 1+3)",
          zero(L.T * eta(n) * L - eta(n)))
    gam = sp.sqrt(1 + dot(w, w, n))
    check("L_{E^w} E = gamma E + w", zero(L * E - gam * E - w))


# -------------------------------------------------------------------- Part B
def part_b():
    print("B. Eagle in the plane of street S and bus B")
    n = 4
    s, b, e = sp.symbols("s b e", real=True)          # rapidities
    hv = lambda r: sp.Matrix([sp.cosh(r), sp.sinh(r), 0, 0])   # unit time-like
    nv = lambda r: sp.Matrix([sp.sinh(r), sp.cosh(r), 0, 0])   # its rest-space unit
    S, B, E = hv(s), hv(b), hv(e)
    w = sp.sinh(b - s) * nv(e)        # boost by rapidity b - s, seen from E
    ch = sp.cosh(b - s)               # = sqrt(1 + w.w) for each w below
    check("for every eagle E in the plane, w = sinh(b-s) n_E solves L_{E^w} S = B",
          zero(boost(E, w, n, ch) * S - B))
    gSB = -dot(S, B, n)
    vSB = B / gSB - S                 # binary velocity (1.4.7), c = 1
    vBS = S / gSB - B
    wS = sp.sinh(b - s) * nv(s)
    wB = sp.sinh(b - s) * nv(b)
    check("eagle = street: w(S,S,B) = gamma_SB v_SB (the binary velocity)",
          zero(wS - gSB * vSB))
    check("eagle = bus:    w(B,S,B) = -gamma_SB v_BS",
          zero(wB + gSB * vBS))
    check("the boosts from E = S, E = B and a general E in the plane coincide",
          zero(boost(S, wS, n, ch) - boost(B, wB, n, ch))
          and zero(boost(S, wS, n, ch) - boost(E, w, n, ch)))


# -------------------------------------------------------------------- Part C
def einstein_add(u, v):
    """Einstein addition u (+) v of 3-velocities (Ungar's convention), c = 1."""
    gu = 1 / sp.sqrt(1 - u.dot(u))
    return (u + v / gu + gu / (1 + gu) * u.dot(v) * u) / (1 + u.dot(v))


def part_c():
    print("C. Eagle outside the plane (exact rationals, 2+1 dimensions)")
    n = 3
    E = sp.Matrix([1, 0, 0])
    uS = sp.Matrix([sp.Rational(3, 5), 0])
    uB = sp.Matrix([0, sp.Rational(4, 5)])
    lift = lambda u: (1 / sp.sqrt(1 - u.dot(u))) * sp.Matrix([1, *u])
    S, B = lift(uS), lift(uB)
    gSB = -dot(S, B, n)
    print(f"    in the eagle's frame u_S = (3/5, 0), u_B = (0, 4/5); gamma_SB = {gSB}")

    w1, w2 = sp.symbols("w1 w2", real=True)
    gw = sp.symbols("g_w", positive=True)
    w = sp.Matrix([0, w1, w2])
    Ex = lambda x: dot(E, x, n)
    wx = lambda x: dot(w, x, n)
    LS = S - ((gw - 1) * Ex(S) - wx(S)) * E - (Ex(S) - wx(S) / (gw + 1)) * w
    eqs = list(LS - B) + [gw**2 - 1 - w1**2 - w2**2]
    sols = sp.solve(eqs, [w1, w2, gw], dict=True)
    check("Concepts' isometry-link problem has exactly one solution", len(sols) == 1)
    sol = sols[0]
    wE = w.subs(sol)
    print(f"    ternary w(E,S,B) = {list(wE)},  w.w = {sp.nsimplify(dot(wE, wE, n))}")
    wbin = B - gSB * S
    print(f"    binary  gamma v_SB = {list(wbin)},  w.w = {dot(wbin, wbin, n)}")
    check("|w(E,S,B)| differs from |gamma_SB v_SB|",
          sp.simplify(dot(wE, wE, n) - dot(wbin, wbin, n)) != 0)
    LE = boost(E, wE, n)
    LS_ = boost(S, wbin, n)
    check("L_{S^w_bin} S = B", zero(LS_ * S - B))
    R = sp.simplify(LS_.inv() * LE)
    check("R = L_{S^w_bin}^{-1} L_{E^w} fixes S and is an isometry",
          zero(R * S - S) and zero(R.T * eta(n) * R - eta(n)))
    cos_t = sp.nsimplify(sp.simplify((R.trace() - 1) / 2))
    print(f"    R is a rotation of S's rest space by angle t, cos t = {cos_t} "
          f"(t = {sp.N(sp.acos(cos_t) * 180 / sp.pi, 4)} deg)")
    check("R is not the identity (a Thomas-Wigner rotation)", cos_t != 1)
    v = sp.Matrix(wE[1:]) / sol[gw]
    check("v = w/gamma_w satisfies Einstein addition v (+) u_S = u_B",
          zero(einstein_add(v, uS) - uB))


# -------------------------------------------------------------------- Part D
def part_d():
    print("D. Metric-free split (Def. 1.4.2) and Galilean additivity (1.4.8)")
    X = sp.Matrix(sp.symbols("x0:4"))
    Y = sp.Matrix(sp.symbols("y0:4"))
    Z = sp.Matrix(sp.symbols("z0:4"))
    a = sp.Matrix(sp.symbols("a0:4")).T          # a clock one-form, no metric
    clock = a / (a * X)[0]                       # any one-form with clock X = 1
    cY = (clock * Y)[0]
    v = Y / cY - X                               # (1.4.7) with this clock
    check("any clock: Y = (clock_X Y)(X + v_XY) and clock_X v_XY = 0 (no metric used)",
          zero(Y - cY * (X + v)) and zero((clock * v)[0]))
    # Galilean case: one clock for all bodies, normalised on each (aX = aY = aZ = 1)
    sub = {sp.Symbol("x0"): 1, sp.Symbol("y0"): 1, sp.Symbol("z0"): 1}
    a1 = sp.Matrix([[1, 0, 0, 0]])
    vel = lambda P, Q: Q.subs(sub) / (a1 * Q.subs(sub))[0] - P.subs(sub)
    check("(1.4.8) with a common clock: v_XY + v_ZX = v_ZY",
          zero(vel(X, Y) + vel(Z, X) - vel(Z, Y)))


# -------------------------------------------------------------------- Part E
def lift(u):
    """Unit time-like vector with spatial velocity u (c = 1)."""
    u = sp.Matrix(u)
    return (1 / sp.sqrt(1 - u.dot(u))) * sp.Matrix([1, *u])


def binary(X, Y, n):
    """Binary velocity (1.4) of Ternary relative velocity: Y/(-Y.X) - X."""
    return Y / (-dot(X, Y, n)) - X


def ternary_22(P, A, B, n):
    """Ternary relative velocity v(P, A, B), eq. (2.2) of Oziewicz 2007."""
    num = dot(P, A + B, n) * (dot(P, B, n) * binary(P, B, n) - dot(P, A, n) * binary(P, A, n))
    return num / (dot(P, A, n) ** 2 + dot(P, B, n) ** 2 - 1 - dot(A, B, n))


def gamma_24(P, A, B, n):
    """gamma_ternary, eq. (2.4) of Oziewicz 2007."""
    a, b, ab = dot(P, A, n), dot(P, B, n), dot(A, B, n)
    return (a**2 + b**2 - ab - 1) / (2 * a * b + ab + 1)


def part_e():
    print("E. Ternary relative velocity (Oziewicz 2007): (2.2)-(2.5), and (1.7.23)")
    n = 4
    R = sp.Rational
    cases = {
        "RV3 case (P at rest, A = (3/5,0,0), B = (0,4/5,0))":
            (lift([0, 0, 0]), lift([R(3, 5), 0, 0]), lift([0, R(4, 5), 0])),
        "general 1+3 case (P, A, B with rational velocities, P moving)":
            (lift([R(1, 7), R(-2, 9), R(1, 5)]), lift([R(2, 5), R(1, 3), 0]),
             lift([R(-1, 4), R(1, 2), R(2, 7)])),
    }
    for name, (P, A, B) in cases.items():
        print(f"    {name}")
        v = ternary_22(P, A, B, n).applyfunc(sp.simplify)
        w = (v / sp.sqrt(1 - dot(v, v, n))).applyfunc(sp.simplify)    # w = gamma_v v
        gw = sp.simplify(sp.sqrt(1 + dot(w, w, n)))
        check("(2.2): P.v = 0 and w = gamma_v v solves L_{P^w} A = B",
              zero(dot(P, v, n)) and zero(boost(P, w, n, gw) * A - B))
        check("(2.3): v(P,B,A) = -v(P,A,B)",
              zero(ternary_22(P, B, A, n) + ternary_22(P, A, B, n)))
        check("(2.4) is the gamma of the boost parameter, sqrt(1 + w.w)",
              zero(gw - gamma_24(P, A, B, n)))
        gAB = sp.simplify(-dot(A, B, n))
        check("... and differs from gamma_binary = -A.B (P outside the plane of A, B)",
              not zero(gw - gAB))
        print(f"      gamma_ternary = {sp.N(gw, 7)}, gamma_binary = {sp.N(gAB, 7)} (numerical display)")
    # P = A: the measuring body as its own observer
    P, A, B = cases["general 1+3 case (P, A, B with rational velocities, P moving)"]
    check("P = A: (2.2) is the binary velocity v_AB and (2.4) is -A.B",
          zero(ternary_22(A, A, B, n) - binary(A, B, n))
          and zero(gamma_24(A, A, B, n) + dot(A, B, n)))
    # coplanar P (Corollary 2.4, Theorem 2.5), symbolic rapidities in one plane,
    # written with t = exp(rapidity) so that every expression is rational
    p, a, b = sp.symbols("p a b", positive=True)
    hv = lambda t: sp.Matrix([(t + 1 / t) / 2, (t - 1 / t) / 2, 0, 0])
    P, A, B = hv(p), hv(a), hv(b)
    vPA, vPB = binary(P, A, n), binary(P, B, n)
    form25 = (vPB - vPA) / (1 - dot(vPB, vPA, n))
    rational_zero = lambda e: all(sp.cancel(x) == 0 for x in sp.Matrix([e]))
    check("coplanar P: (2.2) equals de Abreu-Guerra's (2.5)",
          rational_zero(ternary_22(P, A, B, n) - form25))
    check("coplanar P: gamma_ternary (2.4) = -A.B (Theorem 2.5)",
          rational_zero(gamma_24(P, A, B, n) + dot(A, B, n)))
    # (v_AB + v_BA)^2 in a Gram model of A, B: Mass-centre (1.7.23), talk page 36
    g = sp.symbols("gamma", positive=True)
    G = sp.Matrix([[-1, -g], [-g, -1]])
    s = sp.Matrix([-1, 1 / g]) + sp.Matrix([1 / g, -1])      # v_AB + v_BA on (A, B)
    check("(v_AB + v_BA)^2 = -2(gamma - 1)(1 - 1/gamma^2) = -beta^4 - O(beta^6)",
          zero((s.T * G * s)[0] + 2 * (g - 1) * (1 - 1 / g**2)))


# -------------------------------------------------------------------- Part F
def part_f():
    print("F. Eq. (4.2) of Oziewicz 2007: moving-media electrodynamics")
    n = 4
    u1, u2, u3, E1, E2, E3, bb = sp.symbols("u1 u2 u3 E1 E2 E3 b", real=True)
    u = sp.Matrix([u1, u2, u3])
    E = sp.Matrix([E1, E2, E3])
    Bf = bb * u                                       # u x B = 0, the case of (4.2)
    gam = 1 / sp.sqrt(1 - u.dot(u))
    # F_{mu nu} with F_{i0} = E_i, F_{ij} = eps_{ijk} B_k; field seen by U: F_{mu nu} U^nu
    F = sp.zeros(4, 4)
    for i in range(3):
        F[i + 1, 0], F[0, i + 1] = E[i], -E[i]
        for j in range(3):
            F[i + 1, j + 1] = sum(sp.LeviCivita(i, j, k) * Bf[k] for k in range(3))
    A = sp.Matrix([1, 0, 0, 0])
    Bob = gam * sp.Matrix([1, u1, u2, u3])
    EA = eta(n) * (F * A)                             # raise the index: 4-vectors
    EB = eta(n) * (F * Bob)
    check("groupoid value 0 is the Minkowski product: E_Bob.E_Alice - gamma E_Alice^2 = 0",
          zero(dot(EB, EA, n) - gam * dot(EA, EA, n)))
    Ep = gam * (E + u.cross(Bf)) - gam**2 / (gam + 1) * u.dot(E) * u   # textbook E'
    check("'Lorentz-group' value: E'.E - gamma E^2 = -gamma^2/(gamma+1) (u.E)^2",
          zero(Ep.dot(E) - gam * E.dot(E) + gam**2 / (gam + 1) * u.dot(E) ** 2))
    w = gam * sp.Matrix([0, u1, u2, u3])
    L = boost(A, w, n, gam)
    check("L_{A^gamma u} A = Bob", zero(L * A - Bob))
    pulled = sp.Matrix([0, *Ep])                      # E' placed in Alice's rest space
    check("E' is E_Bob carried into Alice's rest space: L_{A^gamma u} (0, E') = E_Bob",
          zero(L * pulled - EB))


# -------------------------------------------------------------------- Part G
def part_g():
    print("G. GZK threshold as an invariant mass (Theorem MC3, absorption)")
    m, EG = sp.symbols("m E_XG", positive=True)
    # proton X (mass m, c = 1) absorbs a photon G (null): M Z = m X + G.
    # Gram model: g(X,X) = -1, g(X,G) = -E_XG, g(G,G) = 0.
    K = sp.Matrix([[-1, -EG], [-EG, 0]])
    P = sp.Matrix([m, 1])
    M2 = -(P.T * K * P)[0, 0]
    check("M^2 = m^2 + 2 m E_XG (E_XG = photon energy in the proton's frame)",
          zero(M2 - m**2 - 2 * m * EG))
    mp, mpi = sp.Float("938.272"), sp.Float("134.977")       # MeV (PDG)
    Eth = ((mp + mpi) ** 2 - mp**2) / (2 * mp)                 # MeV
    kB, T = sp.Float("8.617333e-5"), sp.Float("2.7255")         # eV/K, K
    eps = sp.Float("2.701") * kB * T                            # mean CMB photon, eV
    gam_th = Eth * 1e6 / (2 * eps)                              # head-on, beta ~ 1
    print(f"    numerical: E_XG at threshold (p gamma -> p pi0) = {sp.N(Eth, 5)} MeV")
    print(f"    numerical: mean CMB photon energy = {sp.N(eps, 3)} eV")
    print(f"    numerical: head-on threshold gamma = {sp.N(gam_th, 3)}, "
          f"proton energy = {sp.N(gam_th * mp * 1e6, 3)} eV")


# -------------------------------------------------------------------- Part W
def part_w():
    print("W. Sizes (numerical): v^2/(2c^2) and the Pioneer comparison")
    cc = sp.Float("299792458")
    for name, v in (("wide binary", 1e3), ("Pioneer 10 at 20 AU", 12e3),
                    ("Milky Way disc", 220e3)):
        print(f"    {name:22s} v = {v / 1e3:6.1f} km/s   gamma - 1 = {sp.N(v**2 / (2 * cc**2), 2)}")
    GM, r = sp.Float("1.32712e20"), 20 * sp.Float("1.495979e11")
    aN = GM / r**2
    print(f"    Newtonian solar acceleration at 20 AU = {sp.N(aN, 3)} m/s^2;"
          f" times (v/c)^2 = {sp.N(aN * (12e3 / cc) ** 2, 2)} m/s^2;"
          f" reported anomaly 8.74e-10 m/s^2")


